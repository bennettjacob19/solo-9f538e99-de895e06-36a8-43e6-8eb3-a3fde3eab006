"""PostgreSQL access layer: schema bootstrap, event writes/queries and index introspection."""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any

import psycopg
from psycopg import sql
from psycopg.rows import dict_row
from psycopg_pool import AsyncConnectionPool

from .config import settings
from .models import IndexView


class Database:
    """Thin async wrapper around a psycopg connection pool."""

    def __init__(self, dsn: str | None = None, schema: str | None = None, table: str | None = None):
        self.dsn = dsn or settings.dsn()
        self.schema = schema or settings.db_schema
        self.table = table or settings.events_table
        self.pool = AsyncConnectionPool(
            self.dsn,
            min_size=1,
            max_size=10,
            open=False,
            kwargs={"row_factory": dict_row, "autocommit": True},
            name="audit-pool",
        )

    # ------------------------------------------------------------------ lifecycle

    async def open(self) -> None:
        await self.pool.open(wait=True, timeout=60)

    async def close(self) -> None:
        await self.pool.close()

    def qualified_table(self) -> sql.Composed:
        return sql.SQL("{}.{}").format(sql.Identifier(self.schema), sql.Identifier(self.table))

    # ------------------------------------------------------------------ bootstrap

    async def ensure_schema(self) -> None:
        """Create the events table. Executed repeatedly at startup, so it is idempotent."""
        async with self.pool.connection() as conn:
            await conn.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(self.schema)))
            await conn.execute(
                sql.SQL(
                    """
                    CREATE TABLE IF NOT EXISTS {table} (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        tenant_id TEXT NOT NULL,
                        event_type TEXT NOT NULL,
                        occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                        payload JSONB NOT NULL DEFAULT '{{}}'::jsonb,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
                    )
                    """
                ).format(table=self.qualified_table())
            )
            # Plain indexes on the filter columns. They make every supported lookup
            # (tenant, type, or time-range) usable before the composite online index
            # exists, and stay out of the way of the managed index lifecycle.
            for column in ("occurred_at", "tenant_id", "event_type"):
                await conn.execute(
                    sql.SQL("CREATE INDEX IF NOT EXISTS {} ON {} ({})").format(
                        sql.Identifier(f"{self.table}_{column}_idx"),
                        self.qualified_table(),
                        sql.Identifier(column),
                    )
                )

    async def health(self) -> str:
        async with self.pool.connection() as conn:
            row = await conn.execute("SELECT 1 AS ok")
            await row.fetchone()
        return "ok"

    # ------------------------------------------------------------------ events

    async def insert_event(
        self,
        tenant_id: str,
        event_type: str,
        occurred_at: datetime | None,
        payload: dict[str, Any],
    ) -> dict[str, Any]:
        async with self.pool.connection() as conn:
            cur = await conn.execute(
                sql.SQL(
                    """
                    INSERT INTO {table} (tenant_id, event_type, occurred_at, payload)
                    VALUES (%s, %s, COALESCE(%s::timestamptz, now()), %s::jsonb)
                    RETURNING id, tenant_id, event_type, occurred_at, payload, created_at
                    """
                ).format(table=self.qualified_table()),
                (tenant_id, event_type, occurred_at, json.dumps(payload)),
            )
            return await cur.fetchone()

    async def insert_events_batch(
        self, rows: list[tuple[str, str, datetime | None, dict[str, Any]]]
    ) -> list[dict[str, Any]]:
        async with self.pool.connection() as conn:
            async with conn.transaction():
                cur = conn.cursor()
                await cur.executemany(
                    sql.SQL(
                        """
                        INSERT INTO {table} (tenant_id, event_type, occurred_at, payload)
                        VALUES (%s, %s, COALESCE(%s::timestamptz, now()), %s::jsonb)
                        """
                    ).format(table=self.qualified_table()),
                    [(t, e, o, json.dumps(p)) for t, e, o, p in rows],
                )
                cur = await conn.execute(
                    sql.SQL(
                        "SELECT id, tenant_id, event_type, occurred_at, payload, created_at "
                        "FROM {table} ORDER BY id DESC LIMIT %s"
                    ).format(table=self.qualified_table()),
                    (len(rows),),
                )
                found = await cur.fetchall()
        return list(reversed(found))

    async def query_events(
        self,
        *,
        tenant_id: str | None,
        event_type: str | None,
        since: datetime | None,
        until: datetime | None,
        limit: int,
        offset: int,
    ) -> list[dict[str, Any]]:
        conditions: list[sql.Composable] = []
        params: list[Any] = []
        if tenant_id:
            conditions.append(sql.SQL("tenant_id = %s"))
            params.append(tenant_id)
        if event_type:
            conditions.append(sql.SQL("event_type = %s"))
            params.append(event_type)
        if since:
            conditions.append(sql.SQL("occurred_at >= %s"))
            params.append(since)
        if until:
            conditions.append(sql.SQL("occurred_at < %s"))
            params.append(until)
        where = (
            sql.SQL(" WHERE ") + sql.SQL(" AND ").join(conditions) if conditions else sql.SQL("")
        )
        # Recent-first ordering keeps demo reads useful; LIMIT/OFFSET keep responses small.
        query = sql.SQL(
            "SELECT id, tenant_id, event_type, occurred_at, payload, created_at FROM {table}{where} "
            "ORDER BY occurred_at DESC, id DESC LIMIT %s OFFSET %s"
        ).format(table=self.qualified_table(), where=where)
        params.extend([limit, offset])
        async with self.pool.connection() as conn:
            cur = await conn.execute(query, params)
            return await cur.fetchall()

    # ------------------------------------------------------------------ index introspection

    async def inspect_index(self, index_name: str) -> IndexView:
        """Report what the PostgreSQL catalog actually contains for this index name."""
        async with self.pool.connection() as conn:
            cur = await conn.execute(
                """
                SELECT c.relname AS name,
                       n.nspname AS schema_name,
                       t.relname AS table_name,
                       i.indisvalid AS valid,
                       i.indisready AS ready,
                       i.indislive AS live,
                       i.indisunique AS unique,
                       c.relkind AS relation_kind,
                       pg_get_indexdef(i.indexrelid) AS definition,
                       pg_get_expr(i.indpred, i.indrelid) AS predicate,
                       pg_get_expr(i.indexprs, i.indrelid) AS expressions
                FROM pg_index i
                JOIN pg_class c ON c.oid = i.indexrelid
                JOIN pg_class t ON t.oid = i.indrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE c.relname = %s AND n.nspname = %s
                """,
                (index_name, self.schema),
            )
            row = await cur.fetchone()
            if row is None:
                cur = await conn.execute(
                    """
                    SELECT c.relname AS name, n.nspname AS schema_name, c.relkind AS relation_kind,
                           NULL AS table_name
                    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                    WHERE c.relname = %s AND n.nspname = %s
                    """,
                    (index_name, self.schema),
                )
                other = await cur.fetchone()
                if other is not None:
                    return IndexView(
                        name=other["name"],
                        schema_name=other["schema_name"],
                        relation_kind=other["relation_kind"],
                        exists=True,
                        matches_expected=False,
                        definition=f"relation kind {other['relation_kind']} is not an index",
                    )
                return IndexView(name=index_name, schema_name=self.schema, exists=False)

            columns = await self._index_columns(conn, index_name)
            return IndexView(
                name=row["name"],
                schema_name=row["schema_name"],
                table_name=row["table_name"],
                exists=True,
                relation_kind=row["relation_kind"],
                is_index=True,
                valid=row["valid"],
                ready=row["ready"],
                live=row["live"],
                unique=row["unique"],
                columns=columns,
                definition=row["definition"],
                predicate=row["predicate"],
                expressions=row["expressions"],
            )

    async def _index_columns(self, conn: psycopg.AsyncConnection, index_name: str) -> list[str]:
        cur = await conn.execute(
            """
            SELECT a.attname AS column_name
            FROM pg_index i
            JOIN pg_class c ON c.oid = i.indexrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(attnum, ord)
            LEFT JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum
            WHERE c.relname = %s AND n.nspname = %s
            ORDER BY k.ord
            """,
            (index_name, self.schema),
        )
        rows = await cur.fetchall()
        return [r["column_name"] for r in rows if r["column_name"] is not None]

    # ------------------------------------------------------------------ maintenance

    async def drop_index_concurrently(self, index_name: str, timeout_seconds: float = 60) -> bool:
        """Remove an index without blocking readers/writers of the events table."""
        conn = await psycopg.AsyncConnection.connect(self.dsn, autocommit=True, row_factory=dict_row)
        try:
            await conn.execute(
                "SELECT set_config('lock_timeout', %s, false)", (f"{int(timeout_seconds * 1000)}ms",)
            )
            await conn.execute(
                sql.SQL("DROP INDEX CONCURRENTLY IF EXISTS {}.{}").format(
                    sql.Identifier(self.schema), sql.Identifier(index_name)
                )
            )
            return True
        finally:
            await conn.close()

    def index_belongs_to_us(self, index_name: str) -> bool:
        """Only the two managed index names may be candidates for automatic cleanup."""
        from .models import INDEX_NAMES

        return index_name in INDEX_NAMES.values()
